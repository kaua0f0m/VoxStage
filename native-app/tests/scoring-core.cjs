const assert = require('node:assert/strict');
const pitch = require('../../audio/pitch-core.js');
function tone(frequency, rate = 12000, duration = .1, amplitude = .2) {
  return Float32Array.from({length:Math.floor(rate * duration)}, (_, i) => amplitude * (Math.sin(2 * Math.PI * frequency * i / rate) + .3 * Math.sin(4 * Math.PI * frequency * i / rate)));
}
for (const rate of [44100,48000]) for (const frequency of [70,110,220,440,880]) {
  const samples = pitch.resample(tone(frequency,rate),rate).slice(0,pitch.FRAME);
  const detected = pitch.detect(samples);
  assert.ok(detected.confidence > .9, `${frequency}Hz confidence ${detected.confidence}`);
  assert.ok(Math.abs(1200 * Math.log2(detected.frequency / frequency)) < 8, `${rate}/${frequency}: ${detected.frequency}`);
}
assert.equal(pitch.detect(new Float32Array(1024)).frequency,0);
assert.equal(pitch.detect(new Float32Array(1024).fill(.3)).frequency,0,'DC is not a note');
assert.equal(pitch.detect(tone(440,12000,.1,.0001)).frequency,0,'Quiet residue must not become a voice');
let seed=15;
const noise=Float32Array.from({length:1024},()=>{seed=(Math.imul(seed,1664525)+1013904223)>>>0;return(seed/2**32-.5)*.5});
assert.equal(pitch.detect(noise).frequency,0,'Aperiodic noise is rejected');
assert.equal(pitch.accuracy(440,440),1);
assert.equal(pitch.accuracy(880,440,75,true),1);
assert.equal(pitch.accuracy(880,440,75,false),0);
assert.equal(pitch.accuracy(440,554.365),0);
assert.equal(pitch.noteName(440),'Lá4');
const reference={start:0,step:.04,frequencies:Float32Array.from({length:200},(_,i)=>i>=75&&i<100?0:440)};
const score=new pitch.Score(reference);
for(let i=0;i<=150;i++)score.add(i*.04,{frequency:440,confidence:1});
assert.equal(score.result().points,2000);
assert.equal(score.result().hitNotes,2);
const visited=score.result().frames;
score.resetTimeline();
for(let i=0;i<=150;i++)score.add(i*.04,{frequency:554.365,confidence:1});
assert.equal(score.result().frames,visited,'Replay cannot farm points');
assert.equal(score.result().points,2000,'Replay cannot rewrite evaluated notes');
const silence=new pitch.Score(reference);
for(let i=0;i<=150;i++)silence.add(i*.04,{frequency:0,confidence:0});
assert.equal(silence.result().points,0,'No singing is zero, not ignored');
assert.equal(silence.result().coverage,0);
const skipped=new pitch.Score(reference);
skipped.add(0,{frequency:440,confidence:1}); skipped.add(6,{frequency:440,confidence:1});
assert.equal(skipped.result().frames,0,'Seeking over a passage is not singing it');
const transposed=new pitch.Score(reference);
for(let i=0;i<50;i++)transposed.add(i*.04,{frequency:440*2**(4/12),confidence:1},{transpose:4});
assert.equal(transposed.result().points,1000);
assert.equal(pitch.referenceAt(reference,-.1),null);
const map = (id, frequency, begin, end) => ({id,start:0,step:.04,duration:8,frequencies:Float32Array.from({length:200},(_,i)=>i>=begin&&i<end?frequency:0)});
const multi=pitch.mergeReferences([map('Lead',440,0,75),map('Back',660,50,150),map('Inst',277,0,200)],'All');
assert.equal(pitch.referenceAt(multi,4).track,'Back','Backing replaces a missing lead');
assert.equal(pitch.referenceAt(multi,7).track,'Inst','Instrumental fills missing vocals');
assert.equal(pitch.referenceAt(multi,2.4,0,660,false).track,'Back','Either simultaneous vocal can be sung');
assert.deepEqual(pitch.referenceCandidates(multi,60).map(c=>c.track),['Lead','Back'],'Instrumental is excluded when a vocal exists');
const both=new pitch.Score(multi);
for(let i=50;i<75;i++)both.add(i*.04,{frequency:660,confidence:1},{acceptOctave:false});
assert.equal(both.result().pitchAccuracy,100,'Backing melody is accepted even if lead has another note');
const noInstrument=new pitch.Score(multi);
for(let i=50;i<75;i++)noInstrument.add(i*.04,{frequency:277,confidence:1},{acceptOctave:false});
assert.equal(noInstrument.result().points,0,'An instrumental note cannot replace a reliable vocal');
const shifted=new pitch.Score(multi);
for(let i=110;i<140;i++)shifted.add(i*.04,{frequency:660*2**(-4/12),confidence:1},{transpose:-4,acceptOctave:false});
assert.equal(shifted.result().points,1000,'All vocal alternatives track transposition');
const cumulative=new pitch.Score(pitch.mergeReferences([map('Lead',440,0,50),map('Back',660,50,100)]));
for(let index=0;index<=50;index++)cumulative.add(index*.04,{frequency:440,confidence:1});
const earned=cumulative.result().points;
for(let index=51;index<100;index++)cumulative.add(index*.04,{frequency:277,confidence:1});
assert.equal(cumulative.result().points,earned,'Later mistakes never remove earned points');
assert.equal(cumulative.result().accuracy,50,'Stars use all chart notes, so missed/skipped notes cannot inflate completion');
for(const [percent,stars,gold] of [[0,0,false],[8.99,0,false],[9,1,false],[17.99,1,false],[18,2,false],[26.99,2,false],[27,3,false],[35.99,3,false],[36,4,false],[44.99,4,false],[45,5,false],[54.99,5,false],[55,5,true],[100,5,true]])assert.deepEqual(pitch.starRating(percent),{stars,gold});
const noteTrack = (notes, levels) => ({id:'Lead',start:.032,step:.04,duration:notes.length*.04,
  frequencies:Float32Array.from(notes,n=>Number.isFinite(n)?pitch.frequencyForNote(n):0),
  levels:Float32Array.from(levels||notes.map(()=>.1)),confidence:Float32Array.from(notes.map(()=>.95))});
const sustained=Array.from({length:200},(_,i)=>69+.65*Math.sin(2*Math.PI*5*i*.04));
const stableNote=pitch.stabilizeReference(noteTrack(sustained));
assert.equal(stableNote.notes.length,1,'Vibrato is one sustained note');
assert.equal(stableNote.notes[0].midi,69);
assert.ok(stableNote.frequencies.every(f=>f===440),'The target is flat, not a sampled vocal curve');
const melody=pitch.stabilizeReference(noteTrack([...Array(12).fill(69),71,71,...Array(12).fill(72),...Array(5).fill(NaN),...Array(5).fill(84)]));
assert.deepEqual(melody.notes.map(note=>note.midi),[69,71,72,84],'Fast 80ms notes and sustained octave changes remain');
assert.equal(melody.notes[1].endIndex-melody.notes[1].startIndex,2);
assert.ok(melody.frequencies.slice(26,31).every(f=>f===0),'Long rests stay empty');
const octaveSpike=pitch.stabilizeReference(noteTrack([...Array(10).fill(69),81,81,...Array(10).fill(69)]));
assert.equal(octaveSpike.notes.length,1,'A short octave error bracketed by a stable note is repaired');
const dropout=[...Array(8).fill(69),NaN,NaN,...Array(8).fill(69)];
assert.equal(pitch.stabilizeReference(noteTrack(dropout)).notes.length,1,'An audible brief detector gap is bridged');
const quietLevels=dropout.map((_,i)=>i===8||i===9?0:.1);
const trueRest=pitch.stabilizeReference(noteTrack(dropout,quietLevels));
assert.equal(trueRest.notes.length,2,'A quiet breath is not bridged');
assert.ok(trueRest.frequencies.slice(8,10).every(f=>f===0));
const longerDropout=[...Array(8).fill(69),...Array(4).fill(NaN),...Array(8).fill(69)];
assert.equal(pitch.stabilizeReference(noteTrack(longerDropout)).notes.length,1,'Audible 160ms gaps within the same note are joined');
assert.equal(pitch.stabilizeReference(noteTrack(longerDropout,longerDropout.map((_,i)=>i>=8&&i<12?0:.1))).notes.length,2,'A 160ms silent breath still separates the notes');
assert.equal(pitch.stabilizeReference(noteTrack([...Array(8).fill(69),...Array(4).fill(70),...Array(8).fill(69)])).notes.length,1,'A short neighboring detour between sustained equal notes is joined');
assert.deepEqual(pitch.stabilizeReference(noteTrack([...Array(8).fill(69),...Array(6).fill(70),...Array(8).fill(69)])).notes.map(n=>n.midi),[69,70,69],'A sustained neighboring note remains a real change');
assert.deepEqual(pitch.stabilizeReference(noteTrack([...Array(8).fill(69),...Array(4).fill(74),...Array(8).fill(69)])).notes.map(n=>n.midi),[69,74,69],'A clear large pitch change is not glued to its neighbors');
assert.ok(pitch.stabilizeReference(noteTrack([69])).frequencies.every(f=>f===0),'An isolated detection does not become a scored note');
const indicator=new pitch.PitchDisplaySmoother(),raw=[],smooth=[];
for(let i=0;i<60;i++) {
  const note=69+(i%2?.35:-.35),detected={frequency:pitch.frequencyForNote(note),confidence:1};
  raw.push(note);smooth.push(pitch.midi(indicator.add(i*.04,detected)));
}
const variance=values=>{const average=values.reduce((a,b)=>a+b,0)/values.length;return values.reduce((sum,v)=>sum+(v-average)**2,0)/values.length;};
assert.ok(variance(smooth.slice(5))<variance(raw.slice(5))*.4,'The display reduces rapid jitter');
indicator.add(2.4,{frequency:pitch.frequencyForNote(73),confidence:1});
assert.ok(Math.abs(pitch.midi(indicator.add(2.44,{frequency:pitch.frequencyForNote(73),confidence:1}))-73)<.1,'A confirmed real pitch jump is shown quickly');
assert.equal(indicator.add(2.48,{frequency:0,confidence:0}),0,'Microphone silence clears the indicator immediately');
assert.equal(indicator.add(2.52,{frequency:440,confidence:.4}),0,'Uncertain microphone input is not invented');
assert.equal(indicator.add(.2,{frequency:220,confidence:1}),220,'Seeking resets the visual filter');
const flatReference=pitch.mergeReferences([stableNote]);
const rawScore=new pitch.Score(flatReference);
for(let i=0;i<100;i++)rawScore.add(i*.04,{frequency:pitch.frequencyForNote(73),confidence:1},{acceptOctave:false});
assert.equal(rawScore.result().points,0,'Visual smoothing cannot award points for a wrong note');
