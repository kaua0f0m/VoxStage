import {readFileSync,writeFileSync,openSync,closeSync,unlinkSync,renameSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomUUID} from 'node:crypto';

export function readBuildInfo(root, version) {
  const publicInfo=JSON.parse(readFileSync(resolve(root,'build-info.json'),'utf8'));
  let info=publicInfo;
  try { info=JSON.parse(readFileSync(resolve(root,'BUILD-DETAILS.json'),'utf8')); }
  catch(error) { if(error.code!=='ENOENT')throw error; }
  if(info.version!==version || publicInfo.version!==version || !info.label || (info.sequence!==undefined&&(!Number.isSafeInteger(info.sequence)||info.sequence<1||!info.buildId))) throw new Error('Build metadata does not match this package. Generate it before packaging.');
  return info;
}
export function createBuildInfo(root, version) {
  const match=/^(\d+)\.(\d+)\.\d+(?:-([A-Za-z0-9.-]+))?$/.exec(version);
  if(!match)throw new Error('Invalid build version.');
  const series=`${match[1]}.${match[2]}`,lock=resolve(root,'.build-sequence.lock');
  let descriptor;
  try { descriptor=openSync(lock,'wx'); }
  catch(error) { if(error.code==='EEXIST')throw new Error('Another build is assigning its version. Retry after it completes.');throw error; }
  try {
    let counters={};
    try { counters=JSON.parse(readFileSync(resolve(root,'BUILD-SEQUENCE.json'),'utf8')); }
    catch(error) { if(error.code!=='ENOENT')throw error; }
    const previous=counters[series]??0;
    if(!Number.isSafeInteger(previous)||previous<0)throw new Error('Invalid build sequence.');
    const sequence=previous+1;
    const rc=/^rc\.(\d+)$/i.exec(match[3]||'');
    const info={version,series,sequence,label:rc?`${series} RC-${rc[1]}`:match[3]?`${series} snapshot ${sequence}`:version,buildId:randomUUID(),builtAt:new Date().toISOString()};
    counters[series]=sequence;
    // Atomic replacement plus a lock avoids duplicate numbers across builds.
    const save=(name,text)=>{const target=resolve(root,name),temporary=target+'.tmp';writeFileSync(temporary,text,'utf8');renameSync(temporary,target);};
    save('BUILD-SEQUENCE.json',JSON.stringify(counters,null,2)+'\n');
    save('BUILD-DETAILS.json',JSON.stringify(info,null,2)+'\n');
    const publicInfo={version,series,label:info.label};
    save('build-info.json',JSON.stringify(publicInfo,null,2)+'\n');
    save('build-info.js','/* Generated by native-app/scripts/build-info.mjs. */\nwindow.VoxStageBuildInfo = Object.freeze('+JSON.stringify(publicInfo)+');\n');
    return info;
  } finally { closeSync(descriptor);unlinkSync(lock); }
}
const entry=process.argv[1]&&resolve(process.argv[1]);
if(entry===fileURLToPath(import.meta.url)) {
  const root=resolve(fileURLToPath(new URL('../..',import.meta.url)));
  const version=process.argv[2]||process.env.VOXSTAGE_BUILD_VERSION||JSON.parse(readFileSync(resolve(root,'package.json'),'utf8')).version;
  const info=process.argv.includes('--reuse')?readBuildInfo(root,version):createBuildInfo(root,version);
  process.stdout.write(JSON.stringify(info)+'\n');
}
